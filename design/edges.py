#!/usr/bin/env python3
"""Draws the three edges every surface of the interface is built from.

    python3 edges.py

NeXTSTEP lit its surfaces from the top left, and every edge in it is two lines
of its grays: a sunken surface, a raised one, and the groove around a titled
group. They go into ../admin/web/parts/ as edge-sunken.svg, edge-raised.svg and
edge-groove.svg, and kit/base.css lays each round a box as a border image two
pixels wide over a border of one.

They are pictures because a browser draws a border and an inset shadow from
two different edges of the box. WebKit rounds a border's width down to whole
device pixels and draws the shadow from the unrounded edge, so wherever the
desk is drawn at a size that does not fall on whole device pixels, such as
125%, the two lines come apart and the background shows between them. A
border image draws both lines from the outer edge of the box, and nothing can
show between them.

The grays are read out of kit/base.css, which is where the palette is
declared, so a picture cannot be in a gray the stylesheet no longer has.
"""

import pathlib
import re

HERE = pathlib.Path(__file__).parent
#: Where the pictures go: the folder the admin serves its pictures from, which
#: build.py also bakes the mockup from.
PARTS = HERE.parent / "admin" / "web" / "parts"
#: Where the four grays are declared, as --white, --light, --dark and --black.
TOKENS = HERE / "kit" / "base.css"

#: What every picture says at the top, so nobody edits the wrong copy.
WRITTEN_BY = ("Generated by design/edges.py. Do not edit by hand: "
              "change the pattern there and run it.")

#: Each edge, pixel by pixel: the two rows and the two columns on each side
#: are the lines, the middle row and column are what is stretched along the
#: box, and the pixel in the middle is never drawn. W is
#: white, D the dark gray and K black, and a dot is where the surface's own
#: background shows. Each is the edge as base.css drew it with a border and a
#: shadow, read off WebKit at 100% pixel for pixel, corners included.
EDGES = {
    # Dark gray outside and black inside on the lit sides, white on the others.
    "sunken": ("DDDDW",
               "DKKKW",
               "DK..W",
               "DK..W",
               "DWWWW"),
    # White on the lit sides, black outside and dark gray inside on the others.
    "raised": ("WWWWK",
               "W..DK",
               "W..DK",
               "WDDDK",
               "WKKKK"),
    # The wall going down and the wall coming back up: dark gray then white on
    # the lit sides, white then dark gray on the others.
    "groove": ("DDDDW",
               "DWWWW",
               "DW.DW",
               "DWDDW",
               "DWWWW"),
}

#: How many pixels the middle row and column of a pattern become in the
#: picture. The browser stretches that middle along each side of the box, and
#: stretched out of a single pixel WebKit at 200% drew part of a field's foot
#: from the pixel beside it, which is the corner's inner line, so a black bar
#: ran along the inside of the field. Ten leave it nothing to take from but the
#: side itself.
MIDDLE = 10

#: Which gray each letter is, by its name in base.css.
LETTERS = {"W": "white", "D": "dark", "K": "black"}

#: How a gray is declared in base.css.
DECLARED = re.compile(r"^\s*--(white|light|dark|black):\s*(#[0-9a-fA-F]{6});", re.M)


def palette():
    """@returns dict from a gray's name in base.css to its value, such as
      {"dark": "#555555"}.

    Raises SystemExit where base.css declares fewer than the four, because a
    picture drawn without one of them is drawn wrong rather than not at all.
    """
    grays = dict(DECLARED.findall(TOKENS.read_text(encoding="utf-8")))
    missing = set(LETTERS.values()) - set(grays)
    if missing:
        raise SystemExit("%s declares no %s" % (TOKENS, ", ".join(sorted(missing))))
    return grays


def widened(pattern):
    """@returns tuple of str, the pattern with its middle row and its middle
      column repeated MIDDLE times."""
    rows = [row[:2] + row[2] * MIDDLE + row[3:] for row in pattern]
    return tuple(rows[:2] + [rows[2]] * MIDDLE + rows[3:])


def drawing(name):
    """@returns str, the SVG of one edge.

    @param name - One of EDGES.

    One path per gray, each a run of single pixels, on a grid of whole pixels
    with crisp edges, so a gray never bleeds into its neighbor however large
    the box is drawn. base.css slices it two pixels in from every side, which
    leaves the corners as the pattern has them and the widened middle to be
    stretched.
    """
    pattern = widened(EDGES[name])
    grays = palette()
    size = len(pattern)
    lines = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
             'viewBox="0 0 %d %d" shape-rendering="crispEdges">' % (size, size, size, size),
             "  <!-- %s -->" % WRITTEN_BY]
    for letter, gray in LETTERS.items():
        pixels = "".join("M%d %dh1v1h-1z" % (column, row)
                         for row, line in enumerate(pattern)
                         for column, found in enumerate(line) if found == letter)
        if pixels:
            lines.append('  <path fill="%s" d="%s"/>' % (grays[gray], pixels))
    lines.append("</svg>")
    return "\n".join(lines) + "\n"


def path(name):
    """@returns pathlib.Path of one edge's picture."""
    return PARTS / f"edge-{name}.svg"


def main():
    # Everything is drawn before anything is written, so a run that cannot
    # finish leaves all three as they were.
    drawn = {name: drawing(name) for name in EDGES}
    for name, document in drawn.items():
        path(name).write_text(document, encoding="utf-8")
    print("wrote " + ", ".join(f"{path(name).name} ({len(document)} bytes)"
                               for name, document in drawn.items()))


if __name__ == "__main__":
    main()
