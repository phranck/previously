#!/usr/bin/env python3
"""Draws the two signs the admin's notifications wear beside the stop sign.

    python3 signs.py

NeXTSTEP 3.3 has one picture of a state, the Workspace's stop sign, which
extract.py takes out of the disk image as stop.png. A notification is an
error, an alert or a piece of information, so the other two are drawn here as
the road signs that go with it: the blue information sign and the warning
triangle. They go into ../admin/web/parts/ as sign-info.svg and
sign-alert.svg. Nothing there is edited by hand.

Both are drawn the way the stop sign is. The canvas is the stop sign's own 61
by 48, and the sign stands where it stands in it, 45 pixels across from the
ninth column. A black edge one pixel up and to the left and a white one one
pixel down and to the right lie behind the face, and a light gray line runs
inside the face two pixels from its edge. The red is the stop sign's, read off
stop.png. The blue is not NeXT's, which had none: it is the darkest blue that
still reads as an information sign beside that red.
"""

import pathlib

HERE = pathlib.Path(__file__).parent
#: Where the drawings go: the folder the admin serves its pictures from.
PARTS = HERE.parent / "admin" / "web" / "parts"

#: What every drawing says at the top, so nobody edits the wrong copy.
WRITTEN_BY = ("Generated by design/signs.py. Do not edit by hand: "
              "change a number there and run it.")

#: The stop sign's canvas, and how far in its sign stands.
CANVAS = (61, 48)
LEFT = 6

BLACK = "#000"
WHITE = "#fff"
RIM = "#aaa"
#: The stop sign's red, read off stop.png.
RED = "#770011"
BLUE = "#10377a"


def behind_and_face(shape, face):
    """The sign's shape three times: the black edge, the white edge, the face.

    @param shape - A function taking a fill and a translation and returning
      the element for it.
    @param face - The face's color.
    """
    return [shape(BLACK, (-1, -1)), shape(WHITE, (1, 1)), shape(face, None)]


def moved(shift):
    """@returns the transform attribute for a shift, or nothing."""
    return f' transform="translate({shift[0]} {shift[1]})"' if shift else ""


def info():
    """A square with its corners cut, and a white i with its foot."""
    outline = "M5 2H43L46 5V43L43 46H5L2 43V5Z"
    return [
        *behind_and_face(
            lambda fill, shift: f'<path d="{outline}" fill="{fill}"{moved(shift)}/>', BLUE),
        f'<path d="M6.5 4.5H41.5L43.5 6.5V41.5L41.5 43.5H6.5L4.5 41.5V6.5Z"'
        f' fill="none" stroke="{RIM}"/>',
        f'<g fill="{WHITE}">'
        '<rect x="21" y="9" width="6" height="6"/>'
        '<rect x="21" y="18" width="6" height="18"/>'
        '<rect x="18" y="18" width="3" height="3"/>'
        '<rect x="18" y="35" width="12" height="3"/></g>',
    ]


def alert():
    """A triangle with rounded corners in the stop sign's red, its white face
    and a black exclamation mark.

    The corners are rounded by drawing each triangle a few pixels in from where
    it ends and stroking it in its own color with round joins, which rounds the
    corners by half the stroke and leaves the sides straight.
    """
    corners = "24,7 42,41 6,41"

    def rounded(points, color, width, shift=None, fill=True):
        painted = color if fill else "none"
        return (f'<polygon points="{points}" fill="{painted}" stroke="{color}"'
                f' stroke-width="{width}" stroke-linejoin="round"{moved(shift)}/>')

    return [
        *behind_and_face(lambda fill, shift: rounded(corners, fill, 8, shift), RED),
        rounded("24,8.5 41.5,40.5 6.5,40.5", RIM, 1, fill=False),
        rounded("24,16.5 35,36.5 13,36.5", WHITE, 4),
        f'<g fill="{BLACK}">'
        '<rect x="22" y="21" width="4" height="10"/>'
        '<rect x="22" y="33" width="4" height="3"/></g>',
    ]


#: Every sign, by the name its file carries after `sign-`.
SIGNS = {"info": info, "alert": alert}


def drawing(name):
    """@returns str, one sign's drawing as the file holds it."""
    width, height = CANVAS
    inside = "".join(f"\n    {element}" for element in SIGNS[name]())
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}"'
            f' viewBox="0 0 {width} {height}" shape-rendering="crispEdges">\n'
            f"  <!-- {WRITTEN_BY} -->\n"
            f'  <g transform="translate({LEFT} 0)">{inside}\n  </g>\n'
            "</svg>\n")


def path(name):
    """@returns pathlib.Path of one sign's drawing."""
    return PARTS / f"sign-{name}.svg"


def main():
    drawn = {name: drawing(name) for name in SIGNS}
    for name, document in drawn.items():
        path(name).write_text(document)
    print("wrote " + ", ".join(path(name).name for name in drawn))


if __name__ == "__main__":
    main()
