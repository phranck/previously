#!/usr/bin/env python3
"""Draws the four Raspberry Pi boards the Info window and Activity Monitor show.

    python3 boards.py

There is one drawing each for the Raspberry Pi 4, the Raspberry Pi 5, the
Compute Module 4 and the Compute Module 5. They go into ../admin/web/parts/ as
board-pi4.svg, board-pi5.svg, board-cm4.svg and board-cm5.svg. Every part sits
where it sits on the real board, brought onto the grid of pixels the drawing
is shown at. The processor is the one part drawn larger than it is, so the
logo on it has room. Nothing there is edited by hand: change a number here
and run it.

They are drawn the way NeXT drew its icons. All four are 72 by 48 pixels, and
every edge but the logo's lies between two pixels, so at that size or at any
whole multiple of it nothing is smoothed. Light falls from the upper left. A
raised part has a white edge on its lit sides and a dark gray one on its
shaded sides inside a black outline, and the two corners where those meet take
the color of its face. The board is a shade darker than the NeXTstation's gray.

None of them carries Raspberry Pi Ltd's logo, because its trademark rules allow
that only beside the sale of its own products (#446). NeXT's logo sits on each
processor instead, as a group with the id next-logo holding the plain paths of
next-logo.svg. The film on previous.li takes it back out of board-pi5.svg by
that id, so the id and the shape of those paths stay.
"""

import pathlib
import re

HERE = pathlib.Path(__file__).parent
#: Where the drawings go: the folder the admin serves its pictures from, which
#: build.py also bakes the mockup from.
PARTS = HERE.parent / "admin" / "web" / "parts"
#: NeXT's logo, in its own units of 2400 by 2000.
NEXT_LOGO = HERE / "next-logo.svg"
#: The id the logo's group carries in every drawing.
NEXT_LOGO_ID = "next-logo"

#: What every drawing says at the top, so nobody edits the wrong copy.
WRITTEN_BY = ("Generated by design/boards.py. Do not edit by hand: "
              "change a number there and run it.")

#: The size of every drawing in pixels. 48 is the height NeXTSTEP drew an icon
#: at. A Raspberry Pi's board fills it with its sockets standing out past two
#: of its edges, and a Compute Module, which has no sockets, stands in the
#: middle of it. app.css gives the picture's box this width.
CANVAS = (72, 48)

#: How much of the height of the processor's face the logo takes, which is
#: all of it: the logo is the one part with detail finer than a pixel, so
#: every pixel it is given shows.
LOGO_SHARE = 1.0

# --- the colors -------------------------------------------------------------
# The four grays NeXTSTEP drew with, and the few the board needs beyond them.

BLACK = "#000"
WHITE = "#fff"
DARK = "#555"
LIGHT = "#aaa"
#: The board, a shade darker than the NeXTstation's gray, and its traces a
#: step lighter than the board.
BOARD = "#4a4a4a"
TRACE = "#616161"
#: A chip's lit edge and its face.
CHIP_LIT = "#3c3c3c"
CHIP_FACE = "#1e1e1e"
#: The gilding of the mounting holes and of every pin and pad.
GOLD = "#d9b13a"
RED_LAMP = "#e0302a"
GREEN_LAMP = "#2ec84a"


# --- writing SVG ------------------------------------------------------------

def number(value):
    """A coordinate as the drawing writes it: whole, or on a pixel's center."""
    text = f"{value:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("", "-0") else text


def rect(x, y, width, height, fill=None):
    """One rectangle, with its fill where it has one of its own rather than
    the group's."""
    painted = f' fill="{fill}"' if fill else ""
    return (f'<rect x="{number(x)}" y="{number(y)}" width="{number(width)}"'
            f' height="{number(height)}"{painted}/>')


def group(fill, elements):
    """Elements that share one fill, as one group."""
    return f'<g fill="{fill}">' + "".join(elements) + "</g>"


class Drawing:
    """One board's drawing, collected in the order it is painted."""

    def __init__(self, name, left=0):
        """
        @param name - The board's short name, which the file is named after.
        @param left - How far in from the canvas's left edge the board stands,
          in whole pixels, so a narrower board stands in the middle.
        """
        self.name = name
        self.left = left
        self.elements = []

    def add(self, *elements):
        self.elements.extend(elements)

    def svg(self):
        """@returns str, the whole document."""
        width, height = CANVAS
        inside = [f"  {element}" for element in self.elements]
        if self.left:
            inside = ([f'  <g transform="translate({self.left} 0)">']
                      + [f"  {line}" for line in inside] + ["  </g>"])
        lines = [
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}"'
            f' viewBox="0 0 {width} {height}" shape-rendering="crispEdges">',
            f"  <!-- {WRITTEN_BY} -->",
            *inside,
            "</svg>",
        ]
        return "\n".join(lines) + "\n"


# --- NeXT's logo -------------------------------------------------------------

def next_logo_paths():
    """@returns list of (fill, path data) pairs, in the order next-logo.svg
    draws them."""
    return re.findall(r'<path fill="(#[0-9a-fA-F]+)" d="([^"]+)"/>', NEXT_LOGO.read_text())


def next_logo_box(paths):
    """The logo's extent in its own units.

    Every command in it is M, C or Z with absolute coordinates, so its numbers
    come in pairs of x and y, and the extremes of those pairs hold the curves.

    @returns (left, top, right, bottom)
    """
    numbers = [float(value) for _, data in paths
               for value in re.findall(r"-?\d+(?:\.\d+)?", data)]
    xs, ys = numbers[0::2], numbers[1::2]
    return min(xs), min(ys), max(xs), max(ys)


# --- the parts ----------------------------------------------------------------
# Every part takes its upper left pixel and its size in whole pixels.

def board(drawing, width, height):
    """The board: a black outline with its corners cut, lit along the top and
    the left, around the board's gray."""
    right, bottom = width - 1, height - 1
    drawing.add(
        f'<path d="M1 0H{right}V1H{width}V{bottom}H{right}V{height}H1V{bottom}H0V1H1Z"'
        f' fill="{BLACK}"/>',
        rect(1, 1, width - 2, height - 2, LIGHT),
        rect(2, 2, width - 3, height - 3, BOARD))


def traces(drawing, data):
    """Traces, as path data of lines one pixel wide along pixel centers."""
    drawing.add(f'<path fill="none" stroke="{TRACE}" d="{data}"/>')


def hole(drawing, x, y, ring=GOLD):
    """A hole through the board, four pixels across, in a plated ring.

    @param ring - Gold for a mounting hole, the light gray of bare metal for
      the smaller ones the Pi 5's cooler is pinned into.
    """
    drawing.add(group(ring, [rect(x + 1, y, 2, 4), rect(x, y + 1, 4, 2)]),
                rect(x + 1, y + 1, 2, 2, BLACK))


def header(drawing, x, y, columns, rows=2):
    """A pin header: a black housing with a gilded pin every second pixel."""
    pins = [rect(x + 1 + 2 * column, y + 1 + 2 * row, 1, 1)
            for row in range(rows) for column in range(columns)]
    drawing.add(rect(x, y, 2 * columns + 1, 2 * rows + 1, BLACK), group(GOLD, pins))


def raised(drawing, x, y, width, height):
    """A part in a metal case, raised the way NeXTSTEP raised a button: black
    outside, white on the lit sides, dark gray on the shaded ones."""
    drawing.add(rect(x, y, width, height, BLACK),
                rect(x + 1, y + 1, width - 2, height - 2, WHITE),
                rect(x + 2, y + 2, width - 3, height - 3, DARK),
                group(LIGHT, [rect(x + 2, y + 2, width - 4, height - 4),
                              rect(x + width - 2, y + 1, 1, 1),
                              rect(x + 1, y + height - 2, 1, 1)]))


def chip(drawing, x, y, width, height):
    """A chip in a black package, its lit edge a step lighter than its face."""
    drawing.add(rect(x, y, width, height, BLACK),
                rect(x + 1, y + 1, width - 2, height - 2, CHIP_LIT),
                group(CHIP_FACE, [rect(x + 2, y + 2, width - 3, height - 3),
                                  rect(x + width - 2, y + 1, 1, 1),
                                  rect(x + 1, y + height - 2, 1, 1)]))


def turned_chip(drawing, center_x, center_y, reach):
    """A chip set at 45 degrees, as a black diamond with its face inside.

    @param reach - How many pixels its corners stand out from its center.
    """
    def diamond(size):
        return [rect(center_x - (size - abs(row)), center_y + row, 2 * (size - abs(row)) + 1, 1)
                for row in range(-size, size + 1)]

    drawing.add(group(BLACK, diamond(reach)), group(CHIP_FACE, diamond(reach - 1)))


def ribbon(drawing, x, y, width, height, contacts=None):
    """A connector for a flat ribbon cable, standing upright: a black body with
    its light latch down the middle.

    @param contacts - "left" or "right" where its gilded contacts show beside
      it, or None where there is no room for them.
    """
    drawing.add(rect(x, y, width, height, BLACK),
                rect(x + 1, y + 1, width - 2, height - 2, LIGHT))
    if contacts:
        column = x - 1 if contacts == "left" else x + width
        drawing.add(group(GOLD, [rect(column, row, 1, 1)
                                 for row in range(y + 1, y + height - 1, 2)]))


def part(drawing, x, y, width, height):
    """A small part in a case of its own, such as a wire connector or a
    crystal: a light face in a black outline."""
    drawing.add(rect(x, y, width, height, BLACK), rect(x + 1, y + 1, width - 2, height - 2, LIGHT))


def small(drawing, *places, color=LIGHT):
    """Small parts with no case to speak of, such as capacitors, each a
    rectangle of one color.

    @param places - (x, y, width, height) of each.
    """
    drawing.add(group(color, [rect(*place) for place in places]))


def pads(drawing, *places):
    """Gilded pads, two pixels square, such as test points."""
    small(drawing, *[(x, y, 2, 2) for x, y in places], color=GOLD)


def antenna_socket(drawing, x, y):
    """The socket an outside antenna plugs into: a gilded pin in a square."""
    drawing.add(rect(x, y, 3, 3, LIGHT), rect(x + 1, y + 1, 1, 1, GOLD))


#: The cells of the code on a label, row by row from the top. It reads as
#: nothing: it has the solid edges a Data Matrix symbol has on its left and its
#: foot, the broken ones it has on its top and its right, and a pattern inside.
#: A smaller label takes the cells nearest its lower left corner, where the
#: solid edges are.
CODE = (
    "10101",
    "11010",
    "10011",
    "11100",
    "11111",
)


def label(drawing, x, y, size):
    """The white label carrying the board's serial number as a code, with a
    pixel of white round the code."""
    cells = size - 2
    rows = CODE[len(CODE) - cells:]
    marks = [rect(x + 1 + column, y + 1 + row, 1, 1)
             for row, line in enumerate(rows) for column, mark in enumerate(line[:cells])
             if mark == "1"]
    drawing.add(rect(x, y, size, size, WHITE), group(BLACK, marks))


def lamp(drawing, x, y, color):
    """One of the board's two lamps."""
    drawing.add(rect(x, y, 2, 1, color))


def processor(drawing, x, y, size):
    """The processor under its metal lid, with NeXT's logo on it.

    The logo is a vector, so it is the one shape drawn off the pixel grid: it
    is smoothed where nothing else is, and the browser draws it at the
    display's own resolution at whatever size the board is shown. It stands
    in the middle of the lid's face and is as tall as the face.
    """
    raised(drawing, x, y, size, size)
    paths = next_logo_paths()
    left, top, right, bottom = next_logo_box(paths)
    face = size - 4
    scale = face * LOGO_SHARE / (bottom - top)
    shift_x = x + size / 2 - scale * (left + right) / 2
    shift_y = y + size / 2 - scale * (top + bottom) / 2
    logo = "".join(f'\n    <path fill="{fill}" d="{data}"/>' for fill, data in paths)
    drawing.add(f'<g id="{NEXT_LOGO_ID}" shape-rendering="geometricPrecision"'
                f' transform="translate({shift_x:.3f} {shift_y:.3f}) scale({scale:.7f})">'
                f'{logo}\n  </g>')


# --- the boards ---------------------------------------------------------------
# Every place is in pixels from the board's upper left corner, with the GPIO
# header along the top. A Raspberry Pi's 85 by 56 millimeters become 68 by 45
# pixels, and a Compute Module's 55 by 40 become 66 by 48. The Pi 4 is measured
# off Raspberry Pi's own illustration of it, the other three off photographs.
# Each processor is a few pixels larger than its place on the real board, and
# the parts around it make room.

#: A Raspberry Pi's board in pixels, and its four mounting holes.
PI_BOARD = (68, 45)
PI_HOLES = ((2, 2), (47, 2), (2, 40), (47, 40))
#: The same for a Compute Module.
CM_BOARD = (66, 48)
CM_HOLES = ((2, 2), (61, 2), (2, 43), (61, 43))
#: How far in a Compute Module stands, so it is in the middle of the canvas.
CM_LEFT = (CANVAS[0] - CM_BOARD[0]) // 2


def plate(drawing, size, holes):
    """The board with its mounting holes."""
    board(drawing, *size)
    for x, y in holes:
        hole(drawing, x, y)


