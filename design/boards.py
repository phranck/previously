#: Every board, by the short name its drawing is called after, which is the
#: name the admin's page asks for.
BOARDS = {
    "pi4": draw_pi4,
    "pi5": draw_pi5,
    "cm4": draw_cm4,
    "cm5": draw_cm5,
}


def path(name):
    """@returns pathlib.Path of one board's drawing."""
    return PARTS / f"board-{name}.svg"


def drawing(name):
    """@returns str, one board's drawing as the file holds it."""
    return BOARDS[name]().svg()


def main():
    # Everything is drawn before anything is written, so a run that cannot
    # finish leaves all four as they were.
    drawn = {name: drawing(name) for name in BOARDS}
    for name, document in drawn.items():
        path(name).write_text(document)
    print("wrote " + ", ".join(f"{path(name).name} ({len(document)} bytes)"
                               for name, document in drawn.items()))


if __name__ == "__main__":
    main()
